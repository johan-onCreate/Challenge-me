CREATE OR REPLACE FUNCTION public.evaluate_challenge_achievements(
  p_user_id UUID,
  p_challenge_id BIGINT
)
RETURNS VOID AS $$
DECLARE
  selected_tier TEXT;
  target_amount NUMERIC;
  total_amount NUMERIC;
BEGIN
  SELECT chosen_tier INTO selected_tier
  FROM public.user_challenges
  WHERE user_id = p_user_id AND challenge_id = p_challenge_id;

  target_amount := NULLIF(
    substring(trim(COALESCE(selected_tier, '')) FROM '^[0-9]+'),
    ''
  )::NUMERIC;

  SELECT COALESCE(SUM(amount), 0) INTO total_amount
  FROM public.challenge_logs
  WHERE user_id = p_user_id AND challenge_id = p_challenge_id;

  INSERT INTO public.user_achievements (achievement_id, challenge_id, user_id)
  SELECT achievement.id, p_challenge_id, p_user_id
  FROM public.challenge_achievements AS achievement
  WHERE achievement.challenge_id = p_challenge_id
    AND (
      (
        achievement.condition_type = 'goal_percentage'
        AND target_amount > 0
        AND total_amount >= target_amount * achievement.condition_value / 100.0
      )
      OR (
        achievement.condition_type = 'daily_record'
        AND EXISTS (
          SELECT 1
          FROM public.challenge_logs AS current_log
          WHERE current_log.user_id = p_user_id
            AND current_log.challenge_id = p_challenge_id
            AND current_log.amount > COALESCE(
              (
                SELECT MAX(previous_log.amount)
                FROM public.challenge_logs AS previous_log
                WHERE previous_log.user_id = p_user_id
                  AND previous_log.challenge_id = p_challenge_id
                  AND previous_log.logged_at <> current_log.logged_at
              ),
              0
            )
        )
      )
    )
  ON CONFLICT (achievement_id, user_id) DO NOTHING;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

CREATE OR REPLACE FUNCTION public.refresh_challenge_achievements_for_logs()
RETURNS TRIGGER AS $$
BEGIN
  PERFORM public.evaluate_challenge_achievements(NEW.user_id, NEW.challenge_id);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

