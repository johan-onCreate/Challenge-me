CREATE OR REPLACE FUNCTION public.refresh_challenge_achievements_for_definition()
RETURNS TRIGGER AS $$
DECLARE
  participant RECORD;
BEGIN
  FOR participant IN
    SELECT user_id
    FROM public.user_challenges
    WHERE challenge_id = NEW.challenge_id
  LOOP
    PERFORM public.evaluate_challenge_achievements(
      participant.user_id,
      NEW.challenge_id
    );
  END LOOP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

