CREATE TABLE IF NOT EXISTS public.challenge_achievements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id BIGINT REFERENCES public.challenges(id) ON DELETE CASCADE NOT NULL,
  name TEXT NOT NULL,
  description TEXT NOT NULL,
  condition_type TEXT NOT NULL CHECK (
    condition_type IN ('goal_percentage', 'daily_record')
  ),
  condition_value INT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT valid_achievement_condition CHECK (
    (condition_type = 'goal_percentage' AND condition_value BETWEEN 1 AND 1000)
    OR (condition_type = 'daily_record' AND condition_value IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS public.user_achievements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  achievement_id BIGINT REFERENCES public.challenge_achievements(id) ON DELETE CASCADE NOT NULL,
  challenge_id BIGINT REFERENCES public.challenges(id) ON DELETE CASCADE NOT NULL,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  unlocked_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (achievement_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.challenge_room_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id BIGINT REFERENCES public.challenges(id) ON DELETE CASCADE NOT NULL,
  room_id BIGINT NOT NULL,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  achievement_id BIGINT REFERENCES public.challenge_achievements(id) ON DELETE SET NULL,
  content TEXT NOT NULL CHECK (char_length(trim(content)) BETWEEN 1 AND 1000),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (achievement_id, user_id),
  UNIQUE (id, challenge_id),
  UNIQUE (id, challenge_id, room_id),
  CONSTRAINT challenge_room_messages_room_challenge_fkey
    FOREIGN KEY (room_id, challenge_id)
    REFERENCES public.challenge_rooms(id, challenge_id)
    ON DELETE CASCADE
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'challenge_room_messages_id_challenge_id_key'
      AND conrelid = 'public.challenge_room_messages'::regclass
  ) THEN
